CREATE DATABASE IF NOT EXISTS perpustakaan_2401020010
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE perpustakaan_2401020010;

CREATE TABLE kategori_buku (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nama_kategori VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE buku (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    kode_buku CHAR(10) NOT NULL UNIQUE,
    judul VARCHAR(100) NOT NULL,
    isbn CHAR(13) NOT NULL UNIQUE,
    tahun_terbit SMALLINT UNSIGNED NOT NULL,
    kategori_buku_id BIGINT UNSIGNED NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_buku_kategori_buku
        FOREIGN KEY (kategori_buku_id)
        REFERENCES kategori_buku(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT chk_tahun_terbit
        CHECK (tahun_terbit BETWEEN 2000 AND 2026)
) ENGINE=InnoDB;
